// ---------------------------------------------------------------- fields
// Resolve every struct's fields, repeating until no struct gains a context:
// a class used both as a request body and in a response is typed for both.
const fieldsOf = new Map();
for (let changed = true; changed;) {
  changed = false;
  for (const [name, st] of structs) {
    const sig = [...st.contexts].sort().join(',');
    if (!sig || st.resolved === sig) continue;
    st.resolved = sig; changed = true;
    // Types first reached from this struct live in its file.
    currentFile = st.file;
    const params = st.contexts.has('params');
    const contexts = [...st.contexts];
    const { props, required } = mergeProps(st.schema);
    const fields = []; const seen = new Set();
    for (const [k, v] of Object.entries(props)) {
      if (v && v.deprecated) continue;
      const isReq = required.has(k);
      const t = resolve(v, { owner: name, field: k, required: isReq, params, contexts });
      let id = ident(k);
      while (seen.has(id)) id += '_';
      seen.add(id);
      let doc = clean(v.description);
      if (v.enum && v.enum.filter((x) => x !== null).length > 1 && !/One of/.test(doc)) doc = (doc ? doc + ' ' : '') + `One of: ${v.enum.filter((x) => x !== null).join(', ')}.`;
      fields.push({ key: k, id, t, doc, required: isReq });
    }
    fieldsOf.set(name, fields);
  }
}

function classCode(name) {
  const st = structs.get(name);
  const fields = fieldsOf.get(name) || [];
  const isParams = st.contexts.has('params');
  const isResp = st.contexts.has('response');
  let code = wrap(clean(st.schema.description), '');
  if (!code) code = isParams ? '/// The request body for the call that takes it.\n' : '/// Returned by the Bachs API.\n';
  code += `class ${name} {\n`;
  if (isParams) {
    const ps = fields.map((f) => (!f.t.nullable && f.t.k !== 'raw' ? `required this.${f.id}` : `this.${f.id}`));
    code += `  /// Creates a ${name}.\n  const ${name}(${ps.length ? `{${ps.join(', ')}}` : ''})${isResp ? ' : raw = const {}' : ''};\n\n`;
  }
  if (isResp) {
    const inits = ['raw = json', ...fields.map((f) => `${f.id} = ${decode(f.t, `json['${f.key}']`)}`)];
    code += `  /// Decodes a ${name} from the API.\n  ${name}.fromJson(Map<String, dynamic> json)\n      : ${inits.join(',\n        ')};\n\n`;
    code += '  /// The full JSON object, including fields this SDK does not type yet.\n  final Map<String, dynamic> raw;\n';
  }
  for (const f of fields) {
    code += wrap(f.doc, '  ');
    code += `  final ${dartType(f.t)} ${f.id};\n`;
  }
  if (isParams) {
    const entries = fields.map((f) => `        '${f.key}': ${encode(f.t, f.id)},`);
    code += `\n  /// Encodes the request body.\n  Map<String, dynamic> toJson() => _compact({\n${entries.join('\n')}\n      });\n`;
  }
  return code + '}\n';
}

function queryCode(name, qps) {
  const fields = [];
  for (const qp of qps) {
    const s = qp.schema || {};
    let doc = clean(qp.description);
    if (s.enum && s.enum.length > 1) doc = (doc ? doc + ' ' : '') + `One of: ${s.enum.filter((x) => x !== null).join(', ')}.`;
    if (qp.required) doc = (doc ? doc + ' ' : '') + 'Required.';
    const type = s.type === 'integer' ? 'int?' : s.type === 'boolean' ? 'bool?' : s.type === 'array' ? 'List<String>?' : 'String?';
    fields.push({ key: qp.name, id: ident(qp.name), type, doc });
  }
  let code = `/// Holds the query parameters for the call.\nclass ${name} {\n  /// Creates the parameters.\n  const ${name}({${fields.map((f) => `this.${f.id}`).join(', ')}});\n\n`;
  for (const f of fields) code += wrap(f.doc, '  ') + `  final ${f.type} ${f.id};\n`;
  code += `\n  Map<String, List<String>> _query() => _queryOf({\n${fields.map((f) => `        '${f.key}': ${f.id},`).join('\n')}\n      });\n}\n`;
  return code;
}


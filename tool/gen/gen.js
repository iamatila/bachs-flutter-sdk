function dartNameFor(schemaName) {
  if (EXISTING[schemaName]) return EXISTING[schemaName];
  if (RENAME[schemaName]) return RENAME[schemaName];
  if (/Pagination$/.test(schemaName) || schemaName === 'PaginationResponse') return 'Pagination';
  let n = schemaName.replace(/^Task/, '');
  if (n.endsWith('ListResponse')) n = n.replace(/ListResponse$/, 'List');
  else if (n.endsWith('Response')) n = n.replace(/Response$/, '');
  else if (n.endsWith('Request')) n = n.replace(/Request$/, 'Params');
  return n;
}

function schemaOf(name) { return MANUAL_SCHEMAS[name] || S[name]; }

function mergeProps(s) {
  const props = {}; const required = new Set(s.required || []);
  const add = (x) => {
    if (!x) return;
    if (x.$ref) x = S[deref(x.$ref)];
    Object.assign(props, x.properties || {});
    (x.required || []).forEach((r) => required.add(r));
    (x.allOf || []).forEach(add);
  };
  add(s);
  return { props, required };
}

// ---------------------------------------------------------------- types
// A resolved type: { k: 'string'|'int'|'double'|'bool'|'time'|'raw'|'class'|'list'|'map', name, elem, nullable }
const RAW = { k: 'raw', nullable: true };

// name -> { schema, contexts: Set('params'|'response'), file }
const structs = new Map();
// Hand-written types used by generated code, by context.
const handwrittenUse = new Map();
let currentFile = '';

function use(name, contexts) {
  const st = structs.get(name);
  if (st) { for (const c of contexts) st.contexts.add(c); return; }
  if (!handwrittenUse.has(name)) handwrittenUse.set(name, new Set());
  for (const c of contexts) handwrittenUse.get(name).add(c);
}

function register(name, schema, file) {
  if (structs.has(name) || existingTypes.has(name)) return;
  structs.set(name, { schema, contexts: new Set(), file });
}

// ensureType returns the Dart class for a named schema, registering it.
function ensureType(schemaName, forceName) {
  const name = forceName || dartNameFor(schemaName);
  if (EXISTING[schemaName] && !forceName) return name;
  if (structs.has(name) || existingTypes.has(name)) return name;
  const s = schemaOf(schemaName);
  if (!s) throw new Error('no schema ' + schemaName);
  const { props } = mergeProps(s);
  if (Object.keys(props).length === 0 && (s.oneOf || s.anyOf)) return null; // raw
  register(name, s, currentFile);
  return name;
}

// resolve maps schema s to a Dart type. params selects request typing
// (optional fields nullable); contexts are marked on referenced classes.
function resolve(s, ctx) {
  const { owner, field, required, params, contexts } = ctx;
  if (!s) return RAW;
  // Every list's paging object maps onto the shared Pagination type.
  if (field === 'pagination') { use('Pagination', contexts); return { k: 'class', name: 'Pagination', nullable: false }; }
  const nullable = !!s.nullable;
  const optional = params ? !required : !(required && !nullable);
  if (s.allOf && s.allOf.length === 1 && s.allOf[0].$ref && !s.properties) return resolve({ ...s.allOf[0], nullable: s.nullable }, ctx);
  if (s.$ref) {
    const name = deref(s.$ref);
    const target = S[name];
    const isObj = target && (target.type === 'object' || target.properties || target.allOf);
    if (!isObj) return resolve({ ...target, nullable: nullable || target.nullable }, ctx);
    const d = ensureType(name);
    if (!d) return RAW;
    use(d, contexts);
    return { k: 'class', name: d, nullable: optional };
  }
  if ((s.oneOf || s.anyOf) && !s.properties) {
    const vs = s.oneOf || s.anyOf;
    const nonNull = vs.filter((v) => !(v.type === 'null' || (v.enum && v.enum.length === 1 && v.enum[0] === null)));
    if (nonNull.length === 1) return resolve({ ...nonNull[0], nullable: true }, ctx);
    if (nonNull.every((v) => v.type === 'string')) return { k: 'string', nullable: params && !required };
    return RAW;
  }
  switch (s.type) {
    case 'string':
      if (s.format === 'date-time') return { k: 'time', nullable: true };
      return { k: 'string', nullable: params && !required };
    case 'integer': return { k: 'int', nullable: params ? !required : nullable };
    case 'number': return { k: 'double', nullable: params ? !required : nullable };
    case 'boolean': return { k: 'bool', nullable: params ? !required : nullable };
    case 'array': {
      const elem = resolve(s.items || {}, { ...ctx, field: singular(field), required: true });
      if (elem.k !== 'time' && elem.k !== 'raw') elem.nullable = false;
      return { k: 'list', elem, nullable: params && !required };
    }
  }
  if (s.type === 'object' || s.properties || s.allOf) {
    const { props } = mergeProps(s);
    if (Object.keys(props).length === 0) {
      const ap = s.additionalProperties;
      if (ap && typeof ap === 'object' && Object.keys(ap).length) {
        const elem = resolve(ap, { ...ctx, field: singular(field), required: true });
        if (elem.k !== 'raw') elem.nullable = false;
        return { k: 'map', elem, nullable: params ? !required : true };
      }
      return { k: 'map', elem: RAW, nullable: params ? !required : true };
    }
    const inlineName = owner + pascal(field);
    register(inlineName, s, structs.get(owner) ? structs.get(owner).file : currentFile);
    use(inlineName, contexts);
    return { k: 'class', name: inlineName, nullable: optional };
  }
  if (s.enum) return { k: 'string', nullable: params && !required };
  return RAW;
}

function dartType(t) {
  let b;
  switch (t.k) {
    case 'string': b = 'String'; break;
    case 'int': b = 'int'; break;
    case 'double': b = 'double'; break;
    case 'bool': b = 'bool'; break;
    case 'time': b = 'DateTime'; break;
    case 'raw': return 'Object?';
    case 'class': b = t.name; break;
    case 'list': b = `List<${dartType(t.elem)}>`; break;
    case 'map': b = `Map<String, ${t.elem.k === 'raw' ? 'dynamic' : dartType(t.elem)}>`; break;
  }
  return t.nullable ? b + '?' : b;
}

function decode(t, e) {
  switch (t.k) {
    case 'string': return t.nullable ? `_strOrNull(${e})` : `_str(${e})`;
    case 'int': return t.nullable ? `_intOrNull(${e})` : `_int(${e})`;
    case 'double': return t.nullable ? `_doubleOrNull(${e})` : `_doubleOrNull(${e}) ?? 0`;
    case 'bool': return t.nullable ? `_boolOrNull(${e})` : `_bool(${e})`;
    case 'time': return `_time(${e})`;
    case 'raw': return e;
    case 'class': return t.nullable ? `_obj(${e}, ${t.name}.fromJson)` : `${t.name}.fromJson(_map(${e}))`;
    case 'list': {
      const inner = decode(t.elem, 'v');
      const fn = /^_\w+\(v\)$/.test(inner) ? inner.slice(0, -3) : `(v) => ${inner}`;
      const list = `_list(${e}, ${fn})`;
      return t.nullable ? `${e} == null ? null : ${list}` : list;
    }
    case 'map': {
      if (t.elem.k === 'raw') return t.nullable ? `_mapOrNull(${e})` : `_map(${e})`;
      const m = `_mapOf(${e}, (v) => ${decode(t.elem, 'v')})`;
      return t.nullable ? m : `${m} ?? {}`;
    }
  }
}

function encode(t, e) {
  const q = t.nullable ? '?' : '';
  switch (t.k) {
    case 'class': return `${e}${q}.toJson()`;
    case 'time': return `_timeToJson(${e})`;
    case 'list':
      if (t.elem.k === 'class') return `${e}${q}.map((v) => v.toJson()).toList()`;
      if (t.elem.k === 'time') return `${e}${q}.map(_timeToJson).toList()`;
      return e;
    case 'map':
      if (t.elem.k === 'class') return `${e}${q}.map((k, v) => MapEntry(k, v.toJson()))`;
      return e;
    default: return e;
  }
}


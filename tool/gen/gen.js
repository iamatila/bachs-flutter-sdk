const str = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$') + "'";

function clean(desc) {
  if (!desc) return '';
  let d = desc.replace(/\s+/g, ' ').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').trim();
  // First sentences up to ~260 characters. Split only at sentence ends
  // followed by whitespace, so "invoice.paid" or "e.g." never drops text.
  const sentences = d.split(/(?<=[.!?])\s+/);
  let out = '';
  for (const s of sentences) { if ((out + ' ' + s).length > 260 && out) break; out = out ? out + ' ' + s : s; if (out.length > 160) break; }
  // Dartdoc reads [x] as a reference and <x> as HTML; neither is meant here.
  return out.trim().replace(/\[/g, '(').replace(/\]/g, ')').replace(/</g, '‹').replace(/>/g, '›');
}

function wrap(text, indent) {
  if (!text) return '';
  const ws = text.split(' ');
  const lines = []; let cur = '';
  for (const w of ws) { if ((cur + ' ' + w).trim().length > 76 - indent.length && cur) { lines.push(cur); cur = w; } else cur = (cur ? cur + ' ' : '') + w; }
  if (cur) lines.push(cur);
  return lines.map((l) => `${indent}/// ${l}`).join('\n') + '\n';
}

